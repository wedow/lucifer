/* lookup(old, name): the character, or None when the name is not defined */
static PyObject *
prim_ucd_lookup(PyObject *m, PyObject *const *args, Py_ssize_t nargs)
{
    const struct ucd_version *self = nargs == 2 ? version_arg(args[0]) : NULL;
    Py_ssize_t length;
    const char *name = nargs == 2 && PyUnicode_Check(args[1]) ? PyUnicode_AsUTF8AndSize(args[1], &length) : NULL;
    if (name == NULL) {
        return PyErr_Occurred() ? NULL : (lu_err_format(PyExc_TypeError, "lookup(old, name)"), NULL);
    }
    Py_UCS4 code;
    if (length > NAME_MAXLEN || !_getcode(name, (int)length, &code)) {
        return Py_NewRef(Py_None);
    }
    if (UCD_Check(self) && (IS_ALIAS(code) || IS_NAMED_SEQ(code))) {
        return Py_NewRef(Py_None);
    }
    if (IS_NAMED_SEQ(code)) {
        unsigned int index = code - named_sequences_start;
        return PyUnicode_FromKindAndData(PyUnicode_2BYTE_KIND, named_sequences[index].seq,
                                         named_sequences[index].seqlen);
    }
    if (IS_ALIAS(code)) {
        code = name_aliases[code - aliases_start];
    }
    return PyUnicode_FromKindAndData(PyUnicode_4BYTE_KIND, &code, 1);
}

/* lu_ucd_getcode: the code point a \N{name} escape names, for the compiler
   (CPython's capi_getcode with named sequences refused and aliases resolved). */
int
lu_ucd_getcode(const char *name, int namelen, Py_UCS4 *code)
{
    if (!_getcode(name, namelen, code) || IS_NAMED_SEQ(*code)) {
        return 0;
    }
    if (IS_ALIAS(*code)) {
        *code = name_aliases[*code - aliases_start];
    }
    return 1;
}

/* The normalization form as 0 NFD, 1 NFKD, 2 NFC, 3 NFKC, or -1. */
static int
form_arg(PyObject *form)
{
    const char *s = PyUnicode_Check(form) ? PyUnicode_AsUTF8(form) : NULL;
    if (s == NULL) {
        return -1;
    }
    return strcmp(s, "NFD") == 0 ? 0 : strcmp(s, "NFKD") == 0 ? 1 : strcmp(s, "NFC") == 0 ? 2
         : strcmp(s, "NFKC") == 0 ? 3 : -1;
}

static PyObject *
prim_ucd_normalize(PyObject *m, PyObject *const *args, Py_ssize_t nargs)
{
    if (nargs != 3 || !PyUnicode_Check(args[2])) {
        lu_err_format(PyExc_TypeError, "normalize(old, form, unistr)");
        return NULL;
    }
    const struct ucd_version *self = version_arg(args[0]);
    PyObject *input = args[2];
    int form = form_arg(args[1]);
    if (form < 0) {
        lu_err_format(PyExc_ValueError, "invalid normalization form");
        return NULL;
    }
    if (PyUnicode_GET_LENGTH(input) == 0) {
        return Py_NewRef(input);
    }
    if (is_normalized_quickcheck(self, input, form >= 2, form & 1, true) == YES) {
        return Py_NewRef(input);
    }
    return (form >= 2 ? nfc_nfkc : nfd_nfkd)(self, input, form & 1);
}

static PyObject *
prim_ucd_is_normalized(PyObject *m, PyObject *const *args, Py_ssize_t nargs)
{
    if (nargs != 3 || !PyUnicode_Check(args[2])) {
        lu_err_format(PyExc_TypeError, "is_normalized(old, form, unistr)");
        return NULL;
    }
    const struct ucd_version *self = version_arg(args[0]);
    PyObject *input = args[2];
    int form = form_arg(args[1]);
    if (PyUnicode_GET_LENGTH(input) == 0) {
        return Py_NewRef(Py_True);
    }
    if (form < 0) {
        lu_err_format(PyExc_ValueError, "invalid normalization form");
        return NULL;
    }
    QuickcheckResult q = is_normalized_quickcheck(self, input, form >= 2, form & 1, false);
    if (q != MAYBE) {
        return Py_NewRef(q == YES ? Py_True : Py_False);
    }
    PyObject *normal = (form >= 2 ? nfc_nfkc : nfd_nfkd)(self, input, form & 1);
    if (normal == NULL) {
        return NULL;
    }
    int same = PyUnicode_GET_LENGTH(normal) == PyUnicode_GET_LENGTH(input)
        && PyUnicode_KIND(normal) == PyUnicode_KIND(input)
        && memcmp(PyUnicode_DATA(normal), PyUnicode_DATA(input),
                  (size_t)PyUnicode_GET_LENGTH(input) * PyUnicode_KIND(input)) == 0;
    Py_DECREF(normal);
    return Py_NewRef(same ? Py_True : Py_False);
}

