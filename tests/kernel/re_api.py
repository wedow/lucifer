def show(f, *a, **k):
    try:
        r = f(*a, **k)
    except Exception as e:
        r = (type(e).__name__, str(e))
    if isinstance(r, re.Match):
        r = (r.span(), r.groups(), r.groupdict(), r.lastindex, r.lastgroup, r.pos, r.endpos)
    print(r)


