/* The parser under test: _Py_dg_strtod's contract (C-locale decimal grammar,
   no whitespace, no inf/nan, ERANGE on overflow only). */
double lu_fast_float_strtod(const char *, char **);

static unsigned long checks, failures;

static int
same(double a, double b)
{
    return memcmp(&a, &b, sizeof a) == 0 || (isnan(a) && isnan(b));
}

static void
fail(const char *what, const char *s, double got, double want)
{
    if (failures++ < 10) {
        fprintf(stderr, "%s: %.120s: got %a, expected %a\n", what, s, got, want);
    }
}

/* s parses to want and consumes exactly `used` bytes. */
static void
verify_prefix(const char *what, const char *s, size_t used, double want)
{
    char *end;
    double got = lu_fast_float_strtod(s, &end);
    checks++;
    if ((size_t)(end - s) != used || !same(got, want)) {
        fail(what, s, got, want);
    }
}

static void
verify(const char *what, const char *s, double want)
{
    verify_prefix(what, s, strlen(s), want);
}

/* The C library's correctly rounded strtod is the reference. */
static void
verify_libc(const char *what, const char *s)
{
    char *end;
    double want = strtod(s, &end);
    verify_prefix(what, s, (size_t)(end - s), want);
}

