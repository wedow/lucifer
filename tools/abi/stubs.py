#!/usr/bin/env python3
"""Generate weak aborting definitions for every exported function.

Usage: tools/abi/stubs.py EXPORTS.tsv INCLUDE_DIR > runtime/capi/stubs.c

Each function the oracle exports (nm T) gets a weak definition with the
prototype its public header declares, found by preprocessing the headers with
cc. Names the headers also define as macros are #undef'd first. A strong definition elsewhere in the runtime replaces the stub at link
time. Functions no public header declares get a `void (void)` stub.
"""

import csv
import re
import subprocess
import sys

HEADERS = ("Python.h", "frameobject.h", "marshal.h", "structmember.h")
EXPORTED = re.compile(r'__attribute__\s*\(\(\s*visibility\s*\(\s*"default"\s*\)\s*\)\)')


def statements(text):
    """Yield top-level declarations; skip anything with a body."""
    start = depth = 0
    for i, c in enumerate(text):
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                start = i + 1
        elif c == ";" and depth == 0:
            yield text[start:i]
            start = i + 1


def strip_attributes(text):
    out, i = [], 0
    while (j := text.find("__attribute__", i)) >= 0:
        out.append(text[i:j])
        k = text.index("(", j)
        depth = 0
        for k in range(k, len(text)):
            depth += {"(": 1, ")": -1}.get(text[k], 0)
            if depth == 0:
                break
        i = k + 1
    out.append(text[i:])
    return " ".join("".join(out).split())


def preprocess(include, *flags):
    source = "".join(f'#include "{h}"\n' for h in HEADERS)
    return subprocess.run(["cc", "-E", "-P", "-std=gnu11", *flags, "-I", include, "-x", "c", "-"],
                          input=source, capture_output=True, text=True, check=True).stdout


def macros(include):
    return {line.split()[1].split("(")[0] for line in preprocess(include, "-dM").splitlines()}


def prototypes(include):
    text = preprocess(include)
    found = {}
    for statement in statements(text):
        if not EXPORTED.search(statement):
            continue
        decl = strip_attributes(statement)
        m = re.fullmatch(r"(?!extern\b)(.*?)\b(\w+)\s*\((.*)\)", decl, re.S)
        if m:
            found.setdefault(m[2], (m[1].strip(), m[3].strip()))
    return found


def main():
    tsv, include = sys.argv[1:3]
    with open(tsv, newline="") as f:
        names = [r["name"] for r in csv.DictReader(f, delimiter="\t") if r["kind"] == "T"]
    protos = prototypes(include)
    defined = macros(include)
    print("/* Generated by tools/abi/stubs.py; do not edit. */")
    for h in HEADERS:
        print(f'#include "{h}"')
    print('#define LU_STUBS     /* the exported names, not lucifer.h\'s inline redirects */')
    print('#include "lucifer.h"\n')
    for name in names:
        if name in protos:
            ret, params = protos[name]
            if name in defined:
                print(f"#undef {name}")
            print(f'LU_STUB {ret} {name}({params}) {{ LU_UNIMPLEMENTED("{name}"); }}')
    print("\n/* Exported by the oracle but declared in no public header. */")
    for name in names:
        if name not in protos:
            print(f'LU_STUB LU_EXPORT void {name}(void) {{ LU_UNIMPLEMENTED("{name}"); }}')


if __name__ == "__main__":
    main()
